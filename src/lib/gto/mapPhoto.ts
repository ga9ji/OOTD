export function inPhotoSight(x: number, z: number): boolean {
  return PHOTO_SIGHTS.some(([sx, sz, from, to, reach]) => {
    const d = Math.hypot(x - sx, z - sz)
    if (d > reach || d < 1e-6) return false
    const b = ((Math.atan2(x - sx, -(z - sz)) * 180) / Math.PI + 360) % 360
    return b >= from && b <= to
  })
}

