// Grand Theft Outfit [部品: city] 現地写真の立ち位置の直し。three/DOM なし。
// 入口: photoStandpoint(x, z, headingDeg) / photoTurn(x, z, headingDeg) / PHOTO_FIXES / PHOTO_LAMPS / PHOTO_STANDS / nearPhotoStand(x, z) / PHOTO_SIGHTS / inPhotoSight(x, z)
// 契約: refs/shibuya/index.json の立ち位置は多くが「写っている建物からの推定」で、通り 1 本ぶん外れている物がある。
//       写っている物（ガードまでの距離、手前の壁、見える塔の方角）から起こし直した立ち位置へ、同じ量だけ平行に移す。
//       緯度経度の撮影クエリ（shot.ts）だけが読む。遊ぶ画面には関係しない。

export interface PhotoFix {
  /** index.json の推定位置（ゲーム内の座標） */
  from: [x: number, z: number]
  /** 写真の向き（度） */
  heading: number
  /** 起こし直した立ち位置 */
  to: [x: number, z: number]
  /** 推定位置からこの距離 m 以内の指定に効く */
  radius: number
  /** 写っている物の方角から起こし直した向きと、推定の向きとの差（度、時計回りが＋）。省くと 0 */
  turn?: number
  /** 起こし直した向きそのもの（度）。指定の向きがばらついても同じ向きに決めたいとき。あれば turn より先に効く */
  face?: number
  /** true なら、指定の位置がずれていても to そのものに立つ（平行に移さない。庇の柱や壁のすぐ脇で、数 m のずれが画面を変える所） */
  pin?: boolean
  /** 見上げの角度（度）がこれ以上の指定にだけ効く（同じ推定位置から、見上げの写真だけ別の所で撮られているとき）。省くと角度を問わない */
  minPitch?: number
  /** 向きの差がこの角度（度）以内の指定にだけ効く。省くと HEADING_TOLERANCE（同じ推定位置の写真を向きで分けるとき） */
  tolerance?: number
  /** この時間帯の指定にだけ効く（同じ推定位置・同じ向きの写真が、時間帯ごとに別の所で撮られているとき）。省くと時間帯を問わない */
  time?: PhotoTime[]
}

