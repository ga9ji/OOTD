/** 向きの差（度、0..180） */
const headingGap = (a: number, b: number) => Math.abs(((a - b + 540) % 360) - 180)

/** 撮影の向きの直し（度）。直しの表に当たれば推定の向きとの差を返し、当たらなければ 0 */
export function photoTurn(x: number, z: number, headingDeg: number, pitchDeg = 0, time?: PhotoTime): number {
  const f = matchFix(x, z, headingDeg, pitchDeg, time)
  if (!f) return 0
  return f.face != null ? ((f.face - headingDeg + 540) % 360) - 180 : (f.turn ?? 0)
}

/** 直しの表から、位置・向き・見上げの角度が当たる最初の行 */
function matchFix(x: number, z: number, headingDeg: number, pitchDeg: number, time?: PhotoTime): PhotoFix | null {
  for (const f of PHOTO_FIXES) {
    if (Math.hypot(x - f.from[0], z - f.from[1]) > f.radius || headingGap(headingDeg, f.heading) > (f.tolerance ?? HEADING_TOLERANCE)) continue
    if (f.minPitch != null && pitchDeg < f.minPitch) continue
    if (f.time && !(time && f.time.includes(time))) continue
    return f
  }
  return null
}

/** 撮影の立ち位置。直しの表に当たれば平行に移し、当たらなければそのまま返す */
export function photoStandpoint(x: number, z: number, headingDeg: number, pitchDeg = 0, time?: PhotoTime): { x: number; z: number } {
  const f = matchFix(x, z, headingDeg, pitchDeg, time)
  if (!f) return { x, z }
  return f.pin ? { x: f.to[0], z: f.to[1] } : { x: x + f.to[0] - f.from[0], z: z + f.to[1] - f.from[1] }
}
